def colo_name(code: str) -> str:
    code = code.strip().upper()
    if code in ('', 'N/A', 'NA', 'UNKNOWN'):
        return '未识别（N/A）'
    city = CITIES.get(code)
    return f'{code} · {city}' if city else f'{code} · 暂无城市备注'
